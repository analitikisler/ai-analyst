#!/usr/bin/env bun
// Turns the brand files (../brand/ai/assets, BRAND.md §5, §6) into inline React components for the product UI:
// the ink becomes currentColor, the red point the --color-brand-point token (#C12D30 light, #FA6B6D dark). The paths
// are copied, never redrawn. Run after the brand files change: bun scripts/gen-brand.mjs
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const assets = path.join(here, "..", "..", "brand", "ai", "assets");
const INK = "#17140F";
const POINT = "#C12D30";

async function component(name, file, doc) {
  const svg = await readFile(path.join(assets, file), "utf8");
  const viewBox = /viewBox="([^"]+)"/.exec(svg)[1];
  const title = /<title[^>]*>([^<]+)<\/title>/.exec(svg)[1];
  const paths = [...svg.matchAll(/<path ([^>]*?)\/?>/g)].map(([, attrs]) => {
    const fill = /fill="(#[0-9A-Fa-f]{6})"/.exec(attrs)?.[1]?.toUpperCase();
    if (fill !== INK && fill !== POINT) throw new Error(`${file}: unexpected colour ${fill}`);
    const rest = attrs.replace(/\s*fill="[^"]*"/, "").trim();
    return `      <path fill="${fill === POINT ? "var(--color-brand-point)" : "currentColor"}" ${rest} />`;
  });
  const [, , w, h] = viewBox.split(" ").map(Number);
  return `/** ${doc} From brand/ai/assets/${file}. */
export function ${name}({ height, title = "${title}", className, decorative }: { height: number; title?: string; className?: string; decorative?: boolean }) {
  return (
    <svg viewBox="${viewBox}" height={height} width={(height * ${w}) / ${h}} role={decorative ? undefined : "img"} aria-hidden={decorative || undefined} className={className}>
      {!decorative && <title>{title}</title>}
${paths.join("\n")}
    </svg>
  );
}
`;
}

const out = `// Generated by scripts/gen-brand.mjs from brand/ai/assets (BRAND.md §5, §6). Do not edit by hand.
// On the product UI the logo takes the text colour (currentColor); only the point stays red (--color-brand-point).
${await component("AiAnalystLogo", "lockups/ai-analyst-light.svg", "The ai analyst horizontal lockup.")}
${await component("AnalitikIslerLogo", "master/analitik-isler-light.svg", "The Analitik İşler master logo (wordmark, three flat bars, red point).")}
${await component("AiAnalystEndorsed", "lockups/ai-analyst-endorsed-light.svg", "The endorsed lockup: ai analyst by the Analitik İşler master logo, for the maker line (§6).")}`;
await writeFile(path.join(here, "..", "src", "components", "art", "BrandLogos.tsx"), out);
console.log("wrote src/components/art/BrandLogos.tsx");
